// 从 assets/avatars/manifest.json 生成构建用的内联清单（方案二的 fallback + 结算分配用池）。
//
// 关键：**条目要全**。host.js 结算时给人物写 avatarRef 用的是这份清单，只内联一部分会让
// 同档第 N 个人跨到隔壁档（rc.31 实测：88 分拿到 b5 的图）。所以元数据全量内联，
// 只有前 --inline-data 张带 data URL（断网时还能显示几张），其余按 baseUrl 走 CDN。
//
// 用法：node tools/avatars/emit-manifest.mjs [--inline-data 3]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MANIFEST = path.join(ROOT, 'assets', 'avatars', 'manifest.json');
const TARGET = path.join(ROOT, 'src', 'ui', 'avatar-manifest.generated.js');

const argIdx = process.argv.indexOf('--inline-data');
const WITH_DATA = argIdx > -1 ? Number(process.argv[argIdx + 1]) : 3;

const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
if (manifest.schema !== 1 || !Array.isArray(manifest.items) || !Array.isArray(manifest.tiers)) {
  throw new Error('manifest.json 结构不对（需要 schema=1 / tiers / items）');
}

const withData = new Map();
const items = manifest.items
  .filter((item) => !item.retired)
  .map((item) => {
    const n = withData.get(item.tier) || 0;
    const base = { id: item.id, tier: item.tier, file: item.file, bytes: item.bytes, sha256: item.sha256, retired: false };
    if (n >= WITH_DATA) return base;
    withData.set(item.tier, n + 1);
    const raw = fs.readFileSync(path.join(ROOT, 'assets', 'avatars', item.file));
    return { ...base, data: 'data:image/webp;base64,' + raw.toString('base64') };
  });

const inline = {
  schema: 1,
  version: manifest.version,
  assetRef: manifest.assetRef,
  basePath: manifest.basePath,
  tiers: manifest.tiers,
  items,
};

const body = [
  '// AUTO-GENERATED by tools/avatars/emit-manifest.mjs — 构建用的内联清单。',
  '// 条目全量（结算分配头像要用完整池），前几张带 data URL 供断网兜底，其余按 baseUrl 走 CDN。',
  'export const INLINE_AVATAR_MANIFEST = ' + JSON.stringify(inline) + ';',
  '',
].join('\n');
fs.writeFileSync(TARGET, body, 'utf8');

const perTier = {};
for (const it of items) perTier[it.tier] = (perTier[it.tier] || 0) + 1;
console.log(`EMIT_OK items=${items.length} data=${[...withData.values()].reduce((a, b) => a + b, 0)} ref=${inline.assetRef} ${Buffer.byteLength(body)} B`);
console.log('  per-tier ' + JSON.stringify(perTier));
